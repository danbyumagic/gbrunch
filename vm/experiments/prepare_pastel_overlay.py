#!/usr/bin/env python3
"""Create a private software-Vulkan experiment; never overwrite input images."""
import argparse, hashlib, json, pathlib, shutil, subprocess, tempfile, zipfile
p=argparse.ArgumentParser(description=__doc__)
for n in ['base-view','compat-image','source-manifest','compat-init','vulkan-apex','output']:
    p.add_argument('--'+n,required=True,type=pathlib.Path)
p.add_argument('--expected-apex-sha256',default='b6b33f2f54a682b11ef69ee9d61344ca26a8b148ae0944f06674f94369b2025d')
p.add_argument('--debugfs',default='debugfs')
p.add_argument('--qemu-img',default='qemu-img')
p.add_argument('--qemu-io',default='qemu-io')
a=p.parse_args()
for n in ['base_view','compat_image','source_manifest','compat_init','vulkan_apex']:
    f=getattr(a,n).resolve()
    if not f.is_file() or str(f).startswith('/dev/'): p.error(n+' must be a regular local file')
    setattr(a,n,f)
with a.vulkan_apex.open('rb') as f:
    if hashlib.file_digest(f,'sha256').hexdigest()!=a.expected_apex_sha256: p.error('Cuttlefish Vulkan APEX hash mismatch')
if a.output.exists(): p.error('Output directory must be new')
manifest=json.loads(a.source_manifest.read_text())
parts=[v for v in manifest['appended_partitions'] if v['name']=='GBRUNCH']
if len(parts)!=1: p.error('Manifest must identify exactly one compatibility partition')
part=parts[0]
if part['bytes']!=a.compat_image.stat().st_size or part['offset']%512 or part['offset']<0:
    p.error('Compatibility size/offset mismatch')
a.output.mkdir(parents=True)
img=a.output/'compat.ext4';shutil.copyfile(a.compat_image,img)
rc=a.compat_init.read_text()
rc='\n'.join(l for l in rc.splitlines() if not l.strip().startswith('insmod '))+'\n'
if rc.count('on early-init\n')!=1: p.error('Expected one early-init action')
rc=rc.replace('on early-init\n','on early-init\n    mount none /oem/vulkan.pastel.so /vendor/lib64/hw/vulkan.intel.so bind\n',1)
rcpath=a.output/'init.gbrunch-vm.rc';rcpath.write_text(rc)
def run(args): return subprocess.run([str(v) for v in args],check=True,capture_output=True)
# Temporary paths generated by tempfile are safe for debugfs/qemu-io command parsers.
with tempfile.TemporaryDirectory(prefix='gbrunch-pastel-') as td:
    tmp=pathlib.Path(td)
    payload=tmp/'apex.img'
    with zipfile.ZipFile(a.vulkan_apex) as z: payload.write_bytes(z.read('apex_payload.img'))
    driver=tmp/'driver.so'
    run([a.debugfs,'-R',f'dump /lib64/hw/vulkan.pastel.so {driver}',payload])
    if not driver.is_file() or driver.stat().st_size<1024: p.error('Driver extraction failed')
    init=tmp/'init.rc';init.write_text(rc)
    for cmd in ['rm /init.gbrunch-vm.rc',f'write {init} /init.gbrunch-vm.rc',f'write {driver} /vulkan.pastel.so','ea_set /vulkan.pastel.so security.selinux u:object_r:same_process_hal_file:s0']:
        run([a.debugfs,'-w','-R',cmd,img])
    # debugfs may return zero for errors; verify both file payloads by reading back.
    for inside,source in [('vulkan.pastel.so',driver),('init.gbrunch-vm.rc',init)]:
        readback=tmp/'readback'
        if readback.exists():readback.unlink()
        run([a.debugfs,'-R',f'dump /{inside} {readback}',img])
        if not readback.exists() or readback.read_bytes()!=source.read_bytes():
            p.error('Compatibility file readback failed: '+inside)
    driver_hash=hashlib.sha256(driver.read_bytes()).hexdigest()
    view=(a.output/'pastel.qcow2').resolve()
    run([a.qemu_img,'create','-f','qcow2','-F','qcow2','-b',a.base_view,view])
    alias=tmp/'compat';alias.symlink_to(img.resolve())
    run([a.qemu_io,'-f','qcow2','-c',f'write -s {alias} {part["offset"]} {part["bytes"]}',view])
(a.output/'experiment.json').write_text(json.dumps({'scope':'local software-renderer probe, not desktop success','driver_sha256':driver_hash,'driver_source':'local Cuttlefish Vulkan APEX','policy_requirement':'init same_process_hal_file:file mounton; enforcing remains enabled','base_view':str(a.base_view),'compatibility_offset':part['offset'],'init_rc':'/oem/init.gbrunch-vm.rc','system_vendor_preservation':'Original backing images unchanged; runtime bind mount only'},indent=2)+'\n')
print(f'Private view: {view}; set androidboot.init_rc=/oem/init.gbrunch-vm.rc')
